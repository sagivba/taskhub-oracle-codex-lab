#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CHANGES="$ROOT/db/changes"
OUT="$ROOT/db/deploy/install/run_all.sql"

{
  echo '-- AUTO-GENERATED by scripts/generate_run_all.sh'
  echo '-- Manual SQLcl clean-install runner. Do not use through MCP R4.'
  echo '-- Review the ordered file list before execution.'
  echo
  find "$CHANGES" -maxdepth 1 -type f -name '[0-9][0-9][0-9][0-9]_*.sql' -printf '%f\n' \
    | sort \
    | while IFS= read -r file; do
        printf '@@../../changes/%s\n' "$file"
      done
} > "$OUT"

printf 'Generated %s\n' "$OUT"
